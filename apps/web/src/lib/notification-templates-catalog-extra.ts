import type { EmailTone } from '@/lib/email-template';
import type { NotificationTemplateSample } from '@/lib/notification-templates-catalog';

const O = 'https://r.bhd-om.com';
const OWNER = 'عبد الحميد الرواحي';
const OWNER_EN = 'Abdul Hamid Al Rawahi';
const GUEST = 'مدرك الرواحي';
const GUEST_EN = 'Mudrik Al Rawahi';

type Spec = {
  id: string;
  category: NotificationTemplateSample['category'];
  tone: EmailTone;
  nameAr: string;
  nameEn: string;
  descriptionAr: string;
  descriptionEn: string;
  subjectAr: string;
  subjectEn: string;
  titleAr: string;
  titleEn: string;
  introAr: string;
  introEn: string;
  ctaAr?: string;
  ctaEn?: string;
  ctaPath?: string;
  /** Force formal footer (no wish) even on a warm tone. */
  warmClosing?: boolean;
  details?: ReadonlyArray<{ labelAr: string; labelEn: string; value: string }>;
};

function entry(spec: Spec): NotificationTemplateSample {
  const ctaPath = spec.ctaPath ?? '/ar/owner';
  const warmClosing = spec.warmClosing;
  return {
    id: spec.id,
    channel: 'both',
    category: spec.category,
    nameAr: spec.nameAr,
    nameEn: spec.nameEn,
    descriptionAr: spec.descriptionAr,
    descriptionEn: spec.descriptionEn,
    editable: false,
    tone: spec.tone,
    email: {
      tone: spec.tone,
      subject: `${spec.subjectAr} · ${spec.subjectEn}`,
      recipientName: GUEST,
      title: `${spec.titleAr} · ${spec.titleEn}`,
      intro: spec.introAr,
      lines: ['— English —', spec.introEn],
      details: (spec.details ?? []).map((d) => ({
        label: `${d.labelAr} / ${d.labelEn}`,
        value: d.value,
      })),
      cta: {
        label: `${spec.ctaAr ?? 'فتح'} · ${spec.ctaEn ?? 'Open'}`,
        url: `${O}${ctaPath}`,
      },
      footnote: 'رسالة آلية من BHD R · Automated message from BHD R',
      ...(warmClosing === undefined ? {} : { warmClosing }),
    },
    whatsapp: {
      tone: spec.tone,
      recipientName: GUEST,
      titleAr: spec.titleAr,
      titleEn: spec.titleEn,
      introAr: spec.introAr,
      introEn: spec.introEn,
      details: spec.details ?? [],
      linkLabelAr: spec.ctaAr ?? 'فتح',
      linkLabelEn: spec.ctaEn ?? 'Open',
      link: `${O}${ctaPath}`,
      ...(warmClosing === undefined ? {} : { warmClosing }),
    },
  };
}

